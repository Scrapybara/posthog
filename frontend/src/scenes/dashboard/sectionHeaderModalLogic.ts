export const sectionHeaderModalLogic = kea<sectionHeaderModalLogicType>([
    path(['scenes', 'dashboard', 'sectionHeaderModalLogic']),
    props({} as SectionHeaderModalLogicProps),
    key((props) => `sectionHeaderModalLogic-${props.dashboard.id}-${props.textTileId}`),
    connect(() => ({ actions: [dashboardsModel, ['updateDashboard']] })),
    listeners(({ props, actions }) => ({
        submitSectionHeaderFailure: ({ error }) => {
            lemonToast.error(`Could not save section header: ${error.message}`)
        },
        submitSectionHeaderSuccess: ({ sectionHeader }: { sectionHeader: SectionHeaderForm }) => {
            actions.resetSectionHeader()
            props.onClose()
            posthog.capture('dashboard section header saved', {
                dashboard_id: props.dashboard.id,
                text_tile_id: props.textTileId === 'new' ? null : props.textTileId,
                is_new: props.textTileId === 'new',
                has_description: !!sectionHeader.description.trim(),
            })
        },
    })),
    forms(({ props, actions }) => ({
        sectionHeader: {
            defaults: (props.textTileId !== 'new'
                ? getExistingSectionHeader(props.dashboard, props.textTileId)
                : { title: '', description: '' }) as SectionHeaderForm,
            errors: ({ title, description }) => ({
                title: !title.trim()
                    ? 'Enter a section title'
                    : title.length > MAX_SECTION_HEADER_TITLE_LENGTH
                      ? `Title is too long (${MAX_SECTION_HEADER_TITLE_LENGTH} characters max)`
                      : null,
                description:
                    description.length > MAX_SECTION_HEADER_DESCRIPTION_LENGTH
                        ? `Description is too long (${MAX_SECTION_HEADER_DESCRIPTION_LENGTH} characters max)`
                        : serializeDashboardSectionHeader({ title, description }).length > MAX_TEXT_TILE_BODY_LENGTH
                          ? 'Shorten the title or description'
                          : null,
            }),
            submit: (formValues) => {
                const body = serializeDashboardSectionHeader(formValues)

                if (props.textTileId === 'new') {
                    const layouts = calculateLayouts([...(props.dashboard.tiles || [])])
                    actions.updateDashboard({
                        id: props.dashboard.id,
                        tiles: [
                            {
                                text: { body },
                                transparent_background: true,
                                layouts: { sm: defaultSmLayoutAtBottom(layouts.sm, 12, 1) },
                            },
                        ],
                    })
                    return
                }

                const tile = props.dashboard.tiles?.find((candidate) => candidate.id === props.textTileId)
                if (!tile?.text) {
                    lemonToast.error('Could not find this section header')
                    return
                }

                actions.updateDashboard({
                    id: props.dashboard.id,
                    tiles: [
                        {
                            id: tile.id,
                            text: { ...tile.text, body },
                            transparent_background: true,
                        },
                    ],
                })
            },
        },
    })),
])
