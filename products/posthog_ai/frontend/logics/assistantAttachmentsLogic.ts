export const assistantAttachmentsLogic = kea<assistantAttachmentsLogicType>([
    props({} as AssistantAttachmentsLogicProps),
    key((props) => props.conversationId),
    path((key) => ['products', 'posthog_ai', 'frontend', 'logics', 'assistantAttachmentsLogic', key]),

    connect(() => ({
        values: [projectLogic, ['currentProjectId']],
    })),

    actions({
        addFiles: (files: File[]) => ({ files }),
        addAttachment: (attachment: AssistantAttachment) => ({ attachment }),
        uploadAttachment: (localId: string) => ({ localId }),
        retryAttachment: (localId: string) => ({ localId }),
        removeAttachment: (localId: string) => ({ localId }),
        setAttachmentUploading: (localId: string) => ({ localId }),
        setAttachmentReady: (localId: string, attachmentId: string) => ({ localId, attachmentId }),
        setAttachmentError: (localId: string, error: string) => ({ localId, error }),
        setSelectionError: (error: string | null) => ({ error }),
        setDragActive: (isActive: boolean) => ({ isActive }),
        beginAttachmentsSend: (attachmentIds: string[]) => ({ attachmentIds }),
        markAttachmentsSendFailed: (attachmentIds: string[]) => ({ attachmentIds }),
        markAttachmentsSent: (attachmentIds: string[]) => ({ attachmentIds }),
    }),

    reducers({
        attachments: [
            [] as AssistantAttachment[],
            {
                addAttachment: (state, { attachment }) => [...state, attachment],
                removeAttachment: (state, { localId }) => state.filter((attachment) => attachment.localId !== localId),
                setAttachmentUploading: (state, { localId }) =>
                    state.map((attachment) =>
                        attachment.localId === localId
                            ? { ...attachment, status: 'uploading', error: undefined, attachmentId: undefined }
                            : attachment
                    ),
                setAttachmentReady: (state, { localId, attachmentId }) =>
                    state.map((attachment) =>
                        attachment.localId === localId
                            ? { ...attachment, status: 'ready', attachmentId, error: undefined }
                            : attachment
                    ),
                setAttachmentError: (state, { localId, error }) =>
                    state.map((attachment) =>
                        attachment.localId === localId
                            ? { ...attachment, status: 'error', error, attachmentId: undefined }
                            : attachment
                    ),
                markAttachmentsSent: (state, { attachmentIds }) =>
                    state.filter(
                        (attachment) => !attachment.attachmentId || !attachmentIds.includes(attachment.attachmentId)
                    ),
            },
        ],
        selectionError: [null as string | null, { setSelectionError: (_, { error }) => error }],
        isDragActive: [false, { setDragActive: (_, { isActive }) => isActive, addFiles: () => false }],
        attachmentsAreSending: [
            false,
            {
                beginAttachmentsSend: () => true,
                markAttachmentsSendFailed: () => false,
                markAttachmentsSent: () => false,
            },
        ],
    }),

    selectors({
        readyAttachmentIds: [
            (s) => [s.attachments],
            (attachments: AssistantAttachment[]): string[] =>
                attachments.flatMap((attachment) =>
                    attachment.status === 'ready' && attachment.attachmentId ? [attachment.attachmentId] : []
                ),
        ],
        attachmentSubmissionDisabledReason: [
            (s) => [s.attachments, s.attachmentsAreSending],
            (attachments: AssistantAttachment[], attachmentsAreSending: boolean): string | undefined => {
                if (attachmentsAreSending) {
                    return 'Wait for images to finish sending'
                }
                if (attachments.some((attachment) => attachment.status === 'uploading')) {
                    return 'Wait for images to finish uploading'
                }
                if (attachments.some((attachment) => attachment.status === 'error')) {
                    return 'Retry or remove failed images before sending'
                }
                return undefined
            },
        ],
        totalBytes: [
            (s) => [s.attachments],
            (attachments: AssistantAttachment[]): number =>
                attachments.reduce((total, attachment) => total + attachment.file.size, 0),
        ],
    }),

    listeners(({ actions, values, props, cache }) => {
        const cleanupPreparedAttachment = (
            attachmentId: string | undefined,
            projectId: string | undefined,
            notifyFailure?: boolean
        ): void => {
            if (!attachmentId || cache.cleanupAttachmentIds.has(attachmentId)) {
                return
            }
            cache.cleanupAttachmentIds.add(attachmentId)
            void deletePreparedAttachment(projectId, props.conversationId, attachmentId).catch(() => {
                if (notifyFailure) {
                    lemonToast.error("Couldn't remove the image from storage. Please try again.")
                }
            })
        }

        return {
            addFiles: ({ files }) => {
                actions.setSelectionError(null)
                const existingKeys = new Set(values.attachments.map((attachment) => attachment.fileKey))
                let selectedCount = values.attachments.length
                let selectedBytes = values.totalBytes
                const validationErrors = new Set<string>()

                for (const file of files) {
                    const fileKey = getFileKey(file)
                    if (existingKeys.has(fileKey)) {
                        validationErrors.add('That image is already attached.')
                        continue
                    }
                    if (!ACCEPTED_IMAGE_TYPES.has(file.type)) {
                        validationErrors.add('Choose a PNG or JPEG image.')
                        continue
                    }
                    if (file.size === 0) {
                        validationErrors.add('Choose a non-empty image.')
                        continue
                    }
                    if (file.size > MAX_ASSISTANT_ATTACHMENT_BYTES) {
                        validationErrors.add('Each image must be 4 MiB or smaller.')
                        continue
                    }
                    if (selectedCount >= MAX_ASSISTANT_ATTACHMENTS) {
                        validationErrors.add(`You can attach up to ${MAX_ASSISTANT_ATTACHMENTS} images.`)
                        continue
                    }
                    if (selectedBytes + file.size > MAX_ASSISTANT_ATTACHMENTS_TOTAL_BYTES) {
                        validationErrors.add('Selected images must total 10 MiB or less.')
                        continue
                    }

                    const localId = uuid()
                    const previewUrl = URL.createObjectURL(file)
                    cache.previewUrls.set(localId, previewUrl)
                    existingKeys.add(fileKey)
                    selectedCount += 1
                    selectedBytes += file.size
                    actions.addAttachment({
                        localId,
                        file,
                        fileKey,
                        previewUrl,
                        status: 'uploading',
                    })
                    actions.uploadAttachment(localId)
                }

                if (validationErrors.size > 0) {
                    actions.setSelectionError([...validationErrors].join(' '))
                }
            },
            uploadAttachment: async ({ localId }) => {
                const attachment = values.attachments.find((candidate) => candidate.localId === localId)
                if (!attachment || cache.uploadControllers.has(localId)) {
                    return
                }
                if (values.currentProjectId == null) {
                    actions.setAttachmentError(localId, getUploadErrorMessage())
                    return
                }

                const abortController = new AbortController()
                cache.uploadControllers.set(localId, abortController)
                let preparedAttachmentId: string | undefined
                const uploadProjectId = String(values.currentProjectId)

                try {
                    const preparedResponse = await assistantAttachmentsPrepareCreate(uploadProjectId, {
                        conversation_id: props.conversationId,
                        attachments: [
                            {
                                file_name: attachment.file.name,
                                content_type: attachment.file.type as AssistantAttachmentContentTypeEnumApi,
                                size: attachment.file.size,
                            },
                        ],
                    })
                    const preparedAttachment: PreparedAttachmentResponse | undefined = preparedResponse.attachments[0]
                    if (!preparedAttachment) {
                        throw new Error('Attachment preparation returned no upload target')
                    }
                    preparedAttachmentId = preparedAttachment.id

                    if (cache.isUnmounted || abortController.signal.aborted) {
                        cleanupPreparedAttachment(preparedAttachmentId, uploadProjectId)
                        return
                    }

                    cache.serverAttachmentIds.set(localId, preparedAttachmentId)
                    cache.serverAttachmentProjectIds.set(localId, uploadProjectId)
                    const uploadBody = new FormData()
                    for (const [field, value] of Object.entries(preparedAttachment.upload_fields)) {
                        uploadBody.append(field, value)
                    }
                    uploadBody.append('file', attachment.file)
                    const uploadResponse = await fetch(preparedAttachment.upload_url, {
                        method: 'POST',
                        body: uploadBody,
                        signal: abortController.signal,
                    })
                    if (!uploadResponse.ok) {
                        throw new Error('Attachment object upload failed')
                    }

                    if (cache.isUnmounted || abortController.signal.aborted) {
                        cleanupPreparedAttachment(preparedAttachmentId, uploadProjectId)
                        return
                    }

                    const finalizedAttachment: FinalizedAttachmentResponse = await assistantAttachmentsFinalizeCreate(
                        uploadProjectId,
                        {
                            conversation_id: props.conversationId,
                            attachment_id: preparedAttachmentId,
                        }
                    )

                    if (cache.isUnmounted || abortController.signal.aborted) {
                        cleanupPreparedAttachment(preparedAttachmentId, uploadProjectId)
                        return
                    }

                    actions.setAttachmentReady(localId, finalizedAttachment.id)
                } catch (error) {
                    if (preparedAttachmentId && (cache.isUnmounted || abortController.signal.aborted)) {
                        cleanupPreparedAttachment(preparedAttachmentId, uploadProjectId)
                        return
                    }
                    posthog.captureException(error, { feature: 'posthog_ai_assistant_attachment' })
                    actions.setAttachmentError(localId, getUploadErrorMessage())
                } finally {
                    if (cache.uploadControllers.get(localId) === abortController) {
                        cache.uploadControllers.delete(localId)
                    }
                }
            },
            retryAttachment: ({ localId }) => {
                const attachment = values.attachments.find((candidate) => candidate.localId === localId)
                if (!attachment || attachment.status !== 'error' || cache.uploadControllers.has(localId)) {
                    return
                }

                const previousServerAttachmentId = cache.serverAttachmentIds.get(localId)
                const previousProjectId = cache.serverAttachmentProjectIds.get(localId)
                cache.serverAttachmentIds.delete(localId)
                cache.serverAttachmentProjectIds.delete(localId)
                cleanupPreparedAttachment(previousServerAttachmentId, previousProjectId)
                actions.setAttachmentUploading(localId)
                actions.uploadAttachment(localId)
            },
            removeAttachment: ({ localId }) => {
                cache.uploadControllers.get(localId)?.abort()
                cache.uploadControllers.delete(localId)

                const previewUrl = cache.previewUrls.get(localId)
                if (previewUrl) {
                    URL.revokeObjectURL(previewUrl)
                    cache.previewUrls.delete(localId)
                }

                const attachmentId = cache.serverAttachmentIds.get(localId)
                const projectId = cache.serverAttachmentProjectIds.get(localId)
                cache.serverAttachmentIds.delete(localId)
                cache.serverAttachmentProjectIds.delete(localId)
                actions.setSelectionError(null)
                cleanupPreparedAttachment(attachmentId, projectId, true)
            },
            markAttachmentsSent: ({ attachmentIds }) => {
                for (const [localId, attachmentId] of cache.serverAttachmentIds.entries()) {
                    if (!attachmentIds.includes(attachmentId)) {
                        continue
                    }
                    cache.serverAttachmentIds.delete(localId)
                    cache.serverAttachmentProjectIds.delete(localId)
                    const previewUrl = cache.previewUrls.get(localId)
                    if (previewUrl) {
                        URL.revokeObjectURL(previewUrl)
                        cache.previewUrls.delete(localId)
                    }
                }
            },
        }
    }),

    afterMount(({ cache }) => {
        cache.isUnmounted = false
        cache.previewUrls = new Map<string, string>()
        cache.serverAttachmentIds = new Map<string, string>()
        cache.serverAttachmentProjectIds = new Map<string, string>()
        cache.cleanupAttachmentIds = new Set<string>()
        cache.uploadControllers = new Map<string, AbortController>()
    }),

    beforeUnmount(({ props, cache }) => {
        cache.isUnmounted = true
        for (const abortController of cache.uploadControllers.values()) {
            abortController.abort()
        }
        cache.uploadControllers.clear()

        for (const [localId, attachmentId] of cache.serverAttachmentIds.entries()) {
            const projectId = cache.serverAttachmentProjectIds.get(localId)
            if (projectId && !cache.cleanupAttachmentIds.has(attachmentId)) {
                cache.cleanupAttachmentIds.add(attachmentId)
                void deletePreparedAttachment(projectId, props.conversationId, attachmentId).catch(() => undefined)
            }
        }
        cache.serverAttachmentIds.clear()
        cache.serverAttachmentProjectIds.clear()

        for (const previewUrl of cache.previewUrls.values()) {
            URL.revokeObjectURL(previewUrl)
        }
        cache.previewUrls.clear()
    }),
])
