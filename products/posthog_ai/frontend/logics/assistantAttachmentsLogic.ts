export const MAX_ASSISTANT_ATTACHMENTS = 4
export const MAX_ASSISTANT_ATTACHMENT_BYTES = 4 * 1024 * 1024
export const MAX_ASSISTANT_ATTACHMENTS_TOTAL_BYTES = 10 * 1024 * 1024
export const ASSISTANT_ATTACHMENT_ACCEPT = 'image/png,image/jpeg'

const ACCEPTED_IMAGE_TYPES = new Set(['image/png', 'image/jpeg'])

type PreparedAttachmentResponse = Awaited<ReturnType<typeof assistantAttachmentsPrepareCreate>>['attachments'][number]
type FinalizedAttachmentResponse = Awaited<ReturnType<typeof assistantAttachmentsFinalizeCreate>>

export interface AssistantAttachmentsLogicProps {
    conversationId: string
}

export interface AssistantAttachment {
    localId: string
    file: File
    fileKey: string
    previewUrl: string
    status: 'uploading' | 'ready' | 'error'
    attachmentId?: string
    error?: string
}

function getFileKey(file: File): string {
    return `${file.name}:${file.type}:${file.size}:${file.lastModified}`
}

function getUploadErrorMessage(): string {
    return "Couldn't upload this image. Retry the upload or remove it."
}

async function deletePreparedAttachment(
    projectId: string | undefined,
    conversationId: string,
    attachmentId: string | undefined
): Promise<void> {
    if (!attachmentId || !projectId) {
        return
    }
    let lastError: unknown
    for (let attempt = 0; attempt < 3; attempt++) {
        try {
            await assistantAttachmentsDeleteCreate(projectId, {
                conversation_id: conversationId,
                attachment_id: attachmentId,
            })
            return
        } catch (error) {
            lastError = error
            if (attempt < 2) {
                await new Promise((resolve) => window.setTimeout(resolve, 250 * 2 ** attempt))
            }
        }
    }
    posthog.captureException(lastError, { feature: 'posthog_ai_assistant_attachment_cleanup' })
    throw lastError
}

